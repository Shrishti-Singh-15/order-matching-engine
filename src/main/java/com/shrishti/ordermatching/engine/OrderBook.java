package com.shrishti.ordermatching.engine;

import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.PriorityQueue;
import java.util.concurrent.locks.ReentrantLock;

/**
 * Thread-safe order book for a single symbol.
 *
 * Uses price-time priority queues for the buy and sell sides:
 *  - Buy side: highest price first, then earliest sequence (FIFO at same price).
 *  - Sell side: lowest price first, then earliest sequence.
 *
 * A single {@link ReentrantLock} guards each matching operation so that
 * concurrent submissions for the same symbol are serialized and price-time
 * priority is preserved, while keeping the critical section limited to the
 * matching loop itself (order validation and persistence happen outside it).
 * Different symbols use different OrderBook instances and therefore different
 * locks, so orders for different symbols can be matched fully in parallel.
 */
public class OrderBook {

    private final String symbol;
    private final ReentrantLock lock = new ReentrantLock();

    private final PriorityQueue<Order> buyQueue = new PriorityQueue<>(
            Comparator.comparing(Order::getPrice, Comparator.reverseOrder())
                    .thenComparingLong(Order::getSequence));

    private final PriorityQueue<Order> sellQueue = new PriorityQueue<>(
            Comparator.comparing(Order::getPrice)
                    .thenComparingLong(Order::getSequence));

    public OrderBook(String symbol) {
        this.symbol = symbol;
    }

    public String getSymbol() { return symbol; }

    /**
     * Submits an order to the book and immediately attempts to match it
     * (and any resting orders it crosses) against the opposite side.
     * Any unfilled remainder rests on the book.
     *
     * @return the trades generated by this submission, in execution order
     */
    public List<Trade> submit(Order incoming) {
        List<Trade> trades = new ArrayList<>();
        lock.lock();
        try {
            PriorityQueue<Order> sameSide = incoming.getSide() == Order.Side.BUY ? buyQueue : sellQueue;
            PriorityQueue<Order> oppositeSide = incoming.getSide() == Order.Side.BUY ? sellQueue : buyQueue;

            while (incoming.getQuantity() > 0 && !oppositeSide.isEmpty()) {
                Order best = oppositeSide.peek();
                boolean crosses = incoming.getSide() == Order.Side.BUY
                        ? incoming.getPrice().compareTo(best.getPrice()) >= 0
                        : incoming.getPrice().compareTo(best.getPrice()) <= 0;

                if (!crosses) {
                    break;
                }

                long matchedQty = Math.min(incoming.getQuantity(), best.getQuantity());
                long buyId = incoming.getSide() == Order.Side.BUY ? incoming.getId() : best.getId();
                long sellId = incoming.getSide() == Order.Side.BUY ? best.getId() : incoming.getId();
                trades.add(new Trade(buyId, sellId, symbol, best.getPrice(), matchedQty));

                incoming.setQuantity(incoming.getQuantity() - matchedQty);
                best.setQuantity(best.getQuantity() - matchedQty);

                if (best.getQuantity() == 0) {
                    oppositeSide.poll();
                }
            }

            if (incoming.getQuantity() > 0) {
                sameSide.offer(incoming);
            }
        } finally {
            lock.unlock();
        }
        return trades;
    }

    public int bookDepth() {
        lock.lock();
        try {
            return buyQueue.size() + sellQueue.size();
        } finally {
            lock.unlock();
        }
    }

    public BigDecimal bestBid() {
        lock.lock();
        try {
            return buyQueue.isEmpty() ? null : buyQueue.peek().getPrice();
        } finally {
            lock.unlock();
        }
    }

    public BigDecimal bestAsk() {
        lock.lock();
        try {
            return sellQueue.isEmpty() ? null : sellQueue.peek().getPrice();
        } finally {
            lock.unlock();
        }
    }
}
